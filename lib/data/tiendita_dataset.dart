/// Función auxiliar para buscar dentro del catálogo maestro por texto o código de barras
List<Product> searchInTienditaCatalog(String query) {
  final clean = query.trim().toLowerCase();
  if (clean.isEmpty) return tienditaMasterCatalog;
  return tienditaMasterCatalog.where((p) {
    return p.name.toLowerCase().contains(clean) ||
        p.category.toLowerCase().contains(clean) ||
        (p.barcode != null && p.barcode!.contains(clean));
  }).toList();
}

/// Función auxiliar para buscar un producto exacto por código de barras
Product? findInTienditaCatalogByBarcode(String barcode) {
  final clean = barcode.trim();
  if (clean.isEmpty) return null;
  try {
    return tienditaMasterCatalog.firstWhere((p) => p.barcode == clean);
  } catch (_) {
    return null;
  }
}
